// Writes better-auth's tables to migrations/0002_better_auth.sql, from the plugins auth.ts configures.
// Run it after changing them: pnpm --filter @app-mcp/registry auth-schema
import { writeFileSync } from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { authOptions, type AuthConfig } from "../src/auth.js";
import type { Database } from "../src/db.js";
import type { Store } from "../src/store.js";

// Every plugin on, so the schema has every table any configuration uses.
const config: AuthConfig = {
  baseURL: "http://localhost:4000",
  secret: "schema",
  mode: "hosted",
  adminEmails: [],
  allowedEmails: [],
  github: { clientId: "-", clientSecret: "-" },
  google: { clientId: "-", clientSecret: "-" },
  oidc: { name: "SSO", issuer: "https://idp.invalid", clientId: "-", clientSecret: "-" },
  password: true,
  dynamicRegistration: true,
};
const db = { auth: new DatabaseSync(":memory:") } as Database;
const options = authOptions(db, {} as Store, config, fetch);
const sql = await (await getMigrations(options)).compileMigrations();

const target = new URL("../migrations/0002_better_auth.sql", import.meta.url);
writeFileSync(target, `-- better-auth's tables. Generated by scripts/auth-schema.ts: don't edit by hand.\n\n${sql.trim()}\n`);
console.log(`Wrote ${target.pathname}`);
